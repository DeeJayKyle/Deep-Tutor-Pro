import { useMemo, useState } from 'react';
import { Download, ListChecks, Plus, Search, Trash2, Wand2 } from 'lucide-react';
import type { BankQuestion, QuestionType } from '../lib/model';
import { api } from '../lib/api';
import { exportDocument } from '../lib/exporters';
import { sortUnits } from '../lib/curriculum';
import { blankQuestion, fromServerQuestion, toBank, TYPE_LABEL } from '../lib/papers';
import { unitLabel } from '../lib/workspace';
import { navigate, useRoute } from '../state/router';
import { remove, update, useWorkspace } from '../state/store';
import { aiProvider, docMeta, plural, sourcesFor, topicCtx, unitCtx, unitReferences } from '../state/helpers';
import { QuestionEditor } from '../ui/QuestionEditor';
import { A, Button, Card, Checkbox, Empty, Field, Input, LinkButton, Page, Select, useAction, useUi } from '../ui/kit';

const letter = (i: number) => String.fromCharCode(65 + i);

export function bankToMarkdown(items: BankQuestion[], withAnswers: boolean): string {
  const out: string[] = [];
  let topic = '';
  items.forEach((q, i) => {
    if (q.topic !== topic) {
      topic = q.topic;
      out.push(`## ${topic || 'General'}`, '');
    }
    out.push(`**${i + 1}.** ${q.prompt.replace(/\n+/g, ' ')} *(${TYPE_LABEL[q.type]}, ${q.marks} marks)*`, '');
    if (q.options.length) out.push(...q.options.map((o, j) => `- ${letter(j)}. ${o}`), '');
    if (withAnswers) {
      if (q.options.length && q.answerIndex !== null) out.push(`**Answer:** ${letter(q.answerIndex)}. ${q.options[q.answerIndex]}`, '');
      else if (q.answer) out.push(`**Answer:** ${q.answer.replace(/\n+/g, ' ')}`, '');
      if (q.markingPoints.length) out.push(...q.markingPoints.map((p) => `- ${p.point} (${p.marks})`), '');
      if (q.solution) out.push(`> ${q.solution.replace(/\n+/g, ' ')}`, '');
    }
  });
  return out.join('\n');
}

export default function BankView() {
  const ws = useWorkspace();
  const route = useRoute();
  const { toast, confirm } = useUi();
  const { busy, run } = useAction();
  const units = sortUnits(ws.units);
  const unitId = route.query.get('unit') ?? '';
  const topicId = route.query.get('topic') ?? '';
  const unit = ws.units.find((u) => u.id === unitId);
  const [type, setType] = useState<'' | QuestionType>('');
  const [q, setQ] = useState('');
  const [count, setCount] = useState(10);
  const [types, setTypes] = useState<QuestionType[]>(['mcq', 'short', 'essay']);
  const [difficulty, setDifficulty] = useState<'easy' | 'moderate' | 'hard' | 'mixed'>('mixed');
  const setFilter = (k: 'unit' | 'topic', v: string) => navigate('/bank', { unit: k === 'unit' ? v || undefined : unitId || undefined, topic: k === 'topic' ? v || undefined : k === 'unit' ? undefined : topicId || undefined }, true);
  const topic = unit?.topics.find((t) => t.id === topicId);

  const items = useMemo(
    () =>
      ws.bank
        .filter((b) => (!unitId || b.unitId === unitId) && (!topicId || b.topicId === topicId) && (!type || b.type === type) && (!q || `${b.prompt} ${b.topic}`.toLowerCase().includes(q.toLowerCase())))
        .sort((a, b) => a.topic.localeCompare(b.topic) || a.createdAt.localeCompare(b.createdAt)),
    [ws.bank, unitId, topicId, type, q],
  );

  const setItem = (nq: BankQuestion) => update((w) => ({ ...w, bank: w.bank.map((b) => (b.id === nq.id ? nq : b)) }));

  const generate = () =>
    run('gen', async () => {
      if (!unit || !topic) throw new Error('Choose a course unit and topic first.');
      const res = await api.questions(
        { unit: unitCtx(unit), topic: topicCtx(topic), count, types, difficulty, sources: sourcesFor(unitReferences(ws, unit), `${topic.title} ${topic.subtopics.join(' ')}`, 30_000) },
        aiProvider(),
      );
      const adds = res.questions.map((sq) => toBank({ ...fromServerQuestion(sq), topic: topic.title }, unit.id, 'ai', topic.id));
      update((w) => ({ ...w, bank: [...w.bank, ...adds] }));
      toast(`${plural(adds.length, 'question')} with solutions added`);
    });

  const exportBank = (withAnswers: boolean) =>
    run(`export-${withAnswers}`, async () => {
      const title = `${unit ? unitLabel(unit) : 'Question bank'}${topic ? ` — ${topic.title}` : ''}${withAnswers ? ' (with answers)' : ''}`;
      const res = await exportDocument('docx', bankToMarkdown(items, withAnswers), docMeta(ws, title, `Question bank · ${plural(items.length, 'question')}`));
      if (res.saved) toast(`Saved ${res.name}`);
    });

  return (
    <Page
      title="Question bank"
      subtitle="Questions with worked solutions and marking schemes for every course unit — generated by AI, collected from your papers, or written by you."
      actions={
        items.length > 0 && (
          <>
            <Button icon={<Download className="h-4 w-4" />} busy={busy === 'export-false'} onClick={() => void exportBank(false)}>
              Export questions
            </Button>
            <Button icon={<Download className="h-4 w-4" />} busy={busy === 'export-true'} onClick={() => void exportBank(true)}>
              With answers
            </Button>
          </>
        )
      }
    >
      <div className="mb-4 grid gap-2 sm:grid-cols-2 lg:grid-cols-4">
        <Select aria-label="Course unit" value={unitId} onChange={(e) => setFilter('unit', e.target.value)}>
          <option value="">All course units</option>
          {units.map((u) => (
            <option key={u.id} value={u.id}>
              {unitLabel(u)}
            </option>
          ))}
        </Select>
        <Select aria-label="Topic" value={topicId} onChange={(e) => setFilter('topic', e.target.value)} disabled={!unit}>
          <option value="">All topics</option>
          {unit?.topics.map((t) => (
            <option key={t.id} value={t.id}>
              {t.title}
            </option>
          ))}
        </Select>
        <Select aria-label="Question type" value={type} onChange={(e) => setType(e.target.value as QuestionType | '')}>
          <option value="">All types</option>
          {Object.entries(TYPE_LABEL).map(([k, v]) => (
            <option key={k} value={k}>
              {v}
            </option>
          ))}
        </Select>
        <div className="relative">
          <Search className="pointer-events-none absolute left-3 top-2.5 h-4 w-4 text-muted" />
          <Input className="pl-9" placeholder="Search questions" value={q} onChange={(e) => setQ(e.target.value)} aria-label="Search questions" />
        </div>
      </div>

      <div className="grid gap-5 xl:grid-cols-[1fr_300px]">
        <div>
          {items.length === 0 ? (
            <Empty icon={<ListChecks className="h-8 w-8" />} title="No questions here yet">
              {unit ? 'Choose a topic and generate questions with solutions, or add your own.' : 'Choose a course unit to start.'}
            </Empty>
          ) : (
            <div className="space-y-2">
              <div className="text-xs text-muted">{plural(items.length, 'question')}</div>
              {items.map((b, i) => (
                <QuestionEditor
                  key={b.id}
                  q={b}
                  number={i + 1}
                  onChange={(nq) => setItem({ ...b, ...nq })}
                  actions={
                    <Button
                      size="sm"
                      variant="ghost"
                      aria-label="Delete question"
                      icon={<Trash2 className="h-3.5 w-3.5" />}
                      onClick={async () => {
                        if (await confirm('Delete this question from the bank?', { danger: true, ok: 'Delete' })) remove('bank', b.id);
                      }}
                    />
                  }
                />
              ))}
            </div>
          )}
        </div>
        <aside className="space-y-4">
          <Card title="Generate with AI">
            {!unit ? (
              <p className="text-sm text-muted">Choose a course unit.</p>
            ) : !unit.topics.length ? (
              <p className="text-sm text-muted">
                <A to={`/units/${unit.id}`}>Add topics</A> to this unit first.
              </p>
            ) : (
              <div className="space-y-3">
                <Field label="Topic">
                  <Select value={topicId} onChange={(e) => setFilter('topic', e.target.value)}>
                    <option value="">Choose…</option>
                    {unit.topics.map((t) => (
                      <option key={t.id} value={t.id}>
                        {t.title}
                      </option>
                    ))}
                  </Select>
                </Field>
                <div className="grid grid-cols-2 gap-2">
                  <Field label="How many">
                    <Input type="number" min={1} max={60} value={count} onChange={(e) => setCount(Math.min(60, Math.max(1, Number(e.target.value) || 1)))} />
                  </Field>
                  <Field label="Difficulty">
                    <Select value={difficulty} onChange={(e) => setDifficulty(e.target.value as typeof difficulty)}>
                      <option value="mixed">Mixed</option>
                      <option value="easy">Easy</option>
                      <option value="moderate">Moderate</option>
                      <option value="hard">Hard</option>
                    </Select>
                  </Field>
                </div>
                <div>
                  <div className="mb-1 text-xs font-medium text-muted">Types</div>
                  <div className="grid grid-cols-2 gap-1">
                    {(Object.keys(TYPE_LABEL) as QuestionType[]).map((t) => (
                      <Checkbox key={t} checked={types.includes(t)} onChange={(v) => setTypes(v ? [...types, t] : types.filter((x) => x !== t))} label={<span className="text-xs">{TYPE_LABEL[t]}</span>} />
                    ))}
                  </div>
                </div>
                <Button className="w-full" variant="primary" icon={<Wand2 className="h-4 w-4" />} busy={busy === 'gen'} disabled={!topic || !types.length} onClick={() => void generate()}>
                  Generate questions
                </Button>
              </div>
            )}
          </Card>
          {unit && (
            <Card title="Add your own">
              <Button
                className="w-full"
                icon={<Plus className="h-4 w-4" />}
                onClick={() => update((w) => ({ ...w, bank: [toBank({ ...blankQuestion('short'), topic: topic?.title ?? '' }, unit.id, 'manual', topic?.id), ...w.bank] }))}
              >
                New question
              </Button>
              <LinkButton className="mt-2 w-full" to="/assessments/new" query={{ unit: unit.id, topic: topicId || undefined }}>
                Build a paper from the bank
              </LinkButton>
            </Card>
          )}
        </aside>
      </div>
    </Page>
  );
}
