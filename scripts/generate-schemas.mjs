// Generate runtime validators from the application's TypeScript data contract.
import ts from 'typescript';
import { readFileSync, writeFileSync } from 'node:fs';
const source = ts.createSourceFile('types.ts', readFileSync('src/types/index.ts', 'utf8'), ts.ScriptTarget.Latest, true);
function schema(node) {
  if (node.kind === ts.SyntaxKind.StringKeyword) return 'z.string()';
  if (node.kind === ts.SyntaxKind.NumberKeyword) return 'z.number().finite()';
  if (node.kind === ts.SyntaxKind.BooleanKeyword) return 'z.boolean()';
  if (ts.isLiteralTypeNode(node)) return `z.literal(${node.literal.getText(source)})`;
  if (ts.isArrayTypeNode(node)) return `z.array(${schema(node.elementType)})`;
  if (ts.isUnionTypeNode(node)) return `z.union([${node.types.map(schema).join(', ')}])`;
  if (ts.isTypeReferenceNode(node)) return `${node.typeName.getText(source)}Schema`;
  if (ts.isTypeLiteralNode(node)) return object(node.members);
  throw new Error(`Unsupported type: ${node.getText(source)}`);
}
function object(members) {
  return `z.object({\n${members.map(m => `  ${m.name.getText(source)}: ${schema(m.type)}${m.questionToken ? '.optional()' : ''},`).join('\n')}\n})`;
}
const definitions = source.statements.filter(n => ts.isInterfaceDeclaration(n) || ts.isTypeAliasDeclaration(n));
writeFileSync('src/services/schemas.ts', '// Generated by npm run schemas. Edit src/types/index.ts, then regenerate.\nimport { z } from "zod";\n\n' + definitions.map(n => `export const ${n.name.text}Schema = ${ts.isInterfaceDeclaration(n) ? object(n.members) : schema(n.type)};`).join('\n\n') + '\n');
